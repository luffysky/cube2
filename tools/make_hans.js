'use strict';
/* Builds src/hans-map.js: every Traditional character whose Simplified form differs, as one string of pairs.
   Needs the opencc-js package: NODE_PATH=<dir with node_modules> node tools/make_hans.js */
const fs = require('fs'), path = require('path');
const OpenCC = require('opencc-js');
const conv = OpenCC.Converter({ from: 'tw', to: 'cn' });
let pairs = '';
for (let c = 0x4E00; c <= 0x9FFF; c++) {
  const t = String.fromCharCode(c), s = conv(t);
  if (s !== t && s.length === 1) pairs += t + s;
}
const out = '/* Traditional to Simplified, character by character. Generated by tools/make_hans.js from OpenCC data (Apache-2.0). */\n' +
  "(function (root) { (root.ZZ = root.ZZ || {}).HANS = '" + pairs + "'; })(typeof window !== 'undefined' ? window : globalThis);\n";
fs.writeFileSync(path.join(__dirname, '..', 'src', 'hans-map.js'), out);
console.log('pairs', pairs.length / 2, 'bytes', Buffer.byteLength(out));
